"""Промпты для мозга и воркеров."""
from .plan import Task

JSON_ONLY = "Ответь ТОЛЬКО JSON-объектом, без пояснений до или после."


def interview(task_text: str) -> str:
    return f"""Ты — ведущий инженер-оркестратор. Пользователь ставит задачу для проекта в текущей папке.
Изучи проект (файлы можно только читать) и задай уточняющие вопросы — только те, без ответа на которые
нельзя качественно спланировать работу. Не больше 5 вопросов, коротко и по делу.

Задача пользователя:
{task_text}

{JSON_ONLY} Формат: {{"questions": ["вопрос 1", "вопрос 2"]}}. Если вопросов нет — {{"questions": []}}."""


def plan(task_text: str, qa: list, full_test_command: str | None, error: str | None = None) -> str:
    answers = "\n".join(f"- Вопрос: {q}\n  Ответ: {a}" for q, a in qa) or "(опрос не проводился)"
    tests_hint = (f"Полный набор тестов проекта запускается так: {full_test_command}"
                  if full_test_command else
                  "Команда полного набора тестов не определена — предложи её в full_test_command.")
    retry = f"\n\nПредыдущий ответ отклонён: {error}\nИсправь и пришли план заново." if error else ""
    return f"""Ты — ведущий инженер-оркестратор. Составь спецификацию и план для задачи в проекте
в текущей папке (файлы можно только читать).

Задача пользователя:
{task_text}

Ответы пользователя на уточняющие вопросы:
{answers}

{tests_hint}

Правила плана:
- Раздели работу на небольшие подзадачи. Каждую выполнит отдельный исполнитель в своей копии проекта;
  подзадачи без взаимных зависимостей выполняются параллельно и НЕ должны править одни и те же файлы.
- depends_on — id подзадач, результат которых нужен этой (они будут слиты до её старта).
- У каждой подзадачи свои тестовые файлы (test_files, пути от корня проекта) и команда test_command,
  которая запускает только их из корня проекта и завершается с ненулевым кодом при падении тестов.
- acceptance — проверяемые критерии приёмки; тесты будут писаться по ним.
- full_test_command — команда запуска всех тестов проекта.
- id: латиница, цифры, «-» и «_».
- spec — краткая спецификация в markdown: что строим, ключевые решения, интерфейсы между подзадачами.

{JSON_ONLY} Формат:
{{"spec": "...", "full_test_command": "...", "tasks": [{{"id": "t1", "title": "...", "description": "...",
"depends_on": [], "test_files": ["..."], "test_command": "...", "acceptance": ["..."]}}]}}{retry}"""


def _task_block(task: Task, spec: str) -> str:
    crit = "\n".join(f"- {a}" for a in task.acceptance)
    return f"""Спецификация проекта:
{spec}

Твоя подзадача [{task.id}] {task.title}
{task.description}

Критерии приёмки:
{crit}

Тестовые файлы: {', '.join(task.test_files)}
Команда тестов подзадачи (из корня проекта): {task.test_command}"""


def _feedback(feedback: str) -> str:
    return f"\n\nОбратная связь от оркестратора:\n{feedback}" if feedback else ""


def tests(task: Task, spec: str, feedback: str = "") -> str:
    return f"""Ты — исполнитель. Работаешь в отдельной копии проекта (текущая папка), только в ней.

{_task_block(task, spec)}

ЭТАП 1 — ТОЛЬКО ТЕСТЫ. Напиши тесты в указанных тестовых файлах: по тесту на каждый критерий приёмки.
Реализацию НЕ пиши: сейчас тесты обязаны падать. Запускать команды ты не можешь — тесты запустит оркестратор.{_feedback(feedback)}

В конце коротко перечисли, что проверяет каждый тест."""


def code(task: Task, spec: str, feedback: str = "") -> str:
    return f"""Ты — исполнитель. Работаешь в отдельной копии проекта (текущая папка), только в ней.

{_task_block(task, spec)}

ЭТАП 2 — КОД. Тесты уже написаны. Напиши реализацию, чтобы команда тестов подзадачи проходила.
Тестовые файлы менять НЕЛЬЗЯ — такие изменения будут откатаны. Не подгоняй код под тесты заглушками.
Запускать команды ты не можешь: после твоего ответа оркестратор сам запустит тесты и пришлёт ошибки.{_feedback(feedback)}

В конце коротко опиши, что изменил."""


def review(task: Task, spec: str, diff: str, test_output: str) -> str:
    return f"""Ты — ведущий инженер-оркестратор. Проверь работу исполнителя (файлы можно только читать).

{_task_block(task, spec)}

Изменения (git diff):
{diff}

Тесты подзадачи зелёные. Вывод:
{test_output}

Проверь, что изменения действительно выполняют все критерии приёмки, тесты проверяют суть,
нет заглушек под тесты и явных ошибок. Стилистические мелочи — не повод отклонять.

{JSON_ONLY} Формат: {{"approved": true, "issues": []}} или {{"approved": false, "issues": ["что исправить"]}}."""
